"""Writers for built meshes: compact binary codec (base64, decoded by src/client/VFX/HDMesh.luau),
Lune-safe Luau data modules, the Meshes index module, OBJ (+vertex colours), GLB and preview JSON.

Binary layout "SVM1" (little endian):
    0   char[4]  magic "SVM1"
    4   u16      version (1)
    6   u16      flags (bit0: palette alpha is meaningful, bit1: u32 indices)
    8   u32      vertex count V
    12  u32      triangle count T
    16  u16      palette count P
    18  u16      reserved (0)
    20  f32[6]   bbox min xyz, bbox max xyz (studs, mesh-local)
    44  u8[P*4]  palette RGBA (sRGB)
    ..  u16[V*3] positions, quantised 0..65535 across the bbox
    ..  u8[V*2]  normals, octahedral
    ..  u8[V]    palette index per vertex
    ..  u16[T*3] (or u32) triangle vertex indices, 0-based, counter-clockwise = front
"""
from __future__ import annotations

import base64
import json
import os
import struct

import numpy as np
import trimesh

from mesher import MeshResult, octa_decode, octa_encode

MAGIC = b"SVM1"
VERSION = 1
B64_LINE = 120


def encode(m: MeshResult) -> bytes:
    V = len(m.vertices)
    T = len(m.faces)
    P = len(m.palette)
    wide = V > 65535
    flags = (2 if wide else 0)
    bmin = m.vertices.min(axis=0)
    bmax = m.vertices.max(axis=0)
    ext = np.maximum(bmax - bmin, 1e-9)
    q = np.clip(np.round((m.vertices - bmin) / ext * 65535.0), 0, 65535).astype("<u2")
    nrm = octa_encode(m.normals)
    out = bytearray()
    out += MAGIC
    out += struct.pack("<HHIIHH", VERSION, flags, V, T, P, 0)
    out += struct.pack("<6f", *bmin.tolist(), *bmax.tolist())
    out += m.palette.astype(np.uint8).tobytes()
    out += q.tobytes()
    out += nrm.astype(np.uint8).tobytes()
    out += m.color_index.astype(np.uint8).tobytes()
    out += m.faces.astype("<u4" if wide else "<u2").tobytes()
    return bytes(out)


def decode(blob: bytes) -> dict:
    """Reference decoder (mirrors HDMesh.Decode) used to verify the encoder."""
    assert blob[:4] == MAGIC, "bad magic"
    version, flags, V, T, P, _ = struct.unpack_from("<HHIIHH", blob, 4)
    box = struct.unpack_from("<6f", blob, 20)
    o = 44
    pal = np.frombuffer(blob, dtype=np.uint8, count=P * 4, offset=o).reshape(P, 4)
    o += P * 4
    q = np.frombuffer(blob, dtype="<u2", count=V * 3, offset=o).reshape(V, 3).astype(np.float64)
    o += V * 6
    nrm = np.frombuffer(blob, dtype=np.uint8, count=V * 2, offset=o).reshape(V, 2)
    o += V * 2
    cidx = np.frombuffer(blob, dtype=np.uint8, count=V, offset=o)
    o += V
    wide = bool(flags & 2)
    idx = np.frombuffer(blob, dtype="<u4" if wide else "<u2", count=T * 3, offset=o).reshape(T, 3)
    o += T * 3 * (4 if wide else 2)
    assert o == len(blob), f"trailing bytes {len(blob) - o}"
    bmin = np.array(box[:3])
    bmax = np.array(box[3:])
    pos = bmin + q / 65535.0 * (bmax - bmin)
    return dict(version=version, positions=pos, normals=octa_decode(nrm), palette=pal, color_index=cidx,
                indices=idx.astype(np.int64), bmin=bmin, bmax=bmax)


def b64_lines(blob: bytes) -> str:
    s = base64.b64encode(blob).decode("ascii")
    return "\n".join(s[i : i + B64_LINE] for i in range(0, len(s), B64_LINE))


def fmt_num(x: float) -> str:
    s = f"{x:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def v3(v) -> str:
    return f"Vector3.new({fmt_num(v[0])}, {fmt_num(v[1])}, {fmt_num(v[2])})"


def write_luau(m: MeshResult, path: str) -> int:
    blob = encode(m)
    chk = decode(blob)
    assert len(chk["positions"]) == len(m.vertices)
    lines = [
        "--!strict",
        f"-- GENERATED by tools/meshgen/build.py - do not edit by hand. HD mesh data: {m.name}.",
        f"-- {m.description}" if m.description else "-- HD mesh data.",
        "-- Lune-safe: plain data. Decode with src/client/VFX/HDMesh.luau (format SVM1, see tools/meshgen/export.py).",
        "-- Units: studs at nominal size, +Y up, front faces -Z, origin = bounding-box centre.",
        "return {",
        f'\tName = "{m.name}",',
        f"\tSize = {v3(m.size)},",
    ]
    if m.hinge is not None:
        lines.append(f"\tHinge = {v3(m.hinge)},")
    if m.anchors:
        lines.append("\tAnchors = {")
        for k in sorted(m.anchors):
            lines.append(f"\t\t{k} = {v3(m.anchors[k])},")
        lines.append("\t},")
    lines += [
        f"\tVertexCount = {len(m.vertices)},",
        f"\tTriangleCount = {len(m.faces)},",
        "\tFormat = 1,",
        "\tData = [[",
        b64_lines(blob),
        "]],",
        "}",
        "",
    ]
    text = "\n".join(lines)
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    return len(text)


def write_index(names: list[str], path: str) -> None:
    names_src = "\n".join(f'\t"{n}",' for n in names)
    text = f"""--!strict
-- HD mesh data index (Lune-safe). The data modules next to this file are GENERATED by
-- tools/meshgen/build.py (SDF sculpt -> marching cubes -> decimation -> vertex colours); this index
-- is regenerated with them. Modules are required lazily, so requiring the index is cheap.
--
-- API:
--   Meshes.Names() -> {{string}}              -- every generated mesh name (SPEC section 18)
--   Meshes.Get(name: string) -> MeshData?      -- the data module, or nil when unknown
--   Meshes.Has(name: string) -> boolean
-- MeshData fields: Name, Size (Vector3 bounding size, studs), Hinge (Vector3? jaw pivot, mesh-local),
-- Anchors ({{[string]: Vector3}}? named points, mesh-local), VertexCount, TriangleCount, Format, Data
-- (base64 "SVM1" payload; decode with StarterPlayerScripts.Client.VFX.HDMesh.Decode).

export type MeshData = {{
\tName: string,
\tSize: Vector3,
\tHinge: Vector3?,
\tAnchors: {{ [string]: Vector3 }}?,
\tVertexCount: number,
\tTriangleCount: number,
\tFormat: number,
\tData: string,
}}

local NAMES: {{ string }} = {{
{names_src}
}}

local known: {{ [string]: boolean }} = {{}}
for _, name in NAMES do
\tknown[name] = true
end

local cache: {{ [string]: MeshData }} = {{}}

local Meshes = {{}}

function Meshes.Names(): {{ string }}
\treturn table.clone(NAMES)
end

function Meshes.Has(name: string): boolean
\treturn known[name] == true
end

function Meshes.Get(name: string): MeshData?
\tlocal cached = cache[name]
\tif cached then
\t\treturn cached
\tend
\tif not known[name] then
\t\treturn nil
\tend
\tlocal module = script:FindFirstChild(name)
\tif module == nil or not module:IsA("ModuleScript") then
\t\treturn nil
\tend
\tlocal ok, data = pcall(require, module :: ModuleScript)
\tif not ok or type(data) ~= "table" then
\t\treturn nil
\tend
\tcache[name] = data :: MeshData
\treturn data :: MeshData
end

return Meshes
"""
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)


def write_obj(m: MeshResult, path: str) -> None:
    lines = [
        f"# {m.name} - UNDERTALE: SOUL VERDICT HD mesh (generated by tools/meshgen/build.py)",
        "# units: studs, +Y up, front faces -Z, origin at bounding-box centre",
        "# vertex colours use the common 'v x y z r g b' extension (sRGB 0..1); importers may ignore them",
        f"# vertices {len(m.vertices)}, triangles {len(m.faces)}",
        f"o {m.name}",
    ]
    for p, c in zip(m.vertices, m.colors):
        lines.append(f"v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f} {c[0]:.4f} {c[1]:.4f} {c[2]:.4f}")
    for n in m.normals:
        lines.append(f"vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}")
    for f in m.faces + 1:
        lines.append(f"f {f[0]}//{f[0]} {f[1]}//{f[1]} {f[2]}//{f[2]}")
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def write_glb(m: MeshResult, path: str) -> None:
    rgba = np.concatenate([np.round(m.colors * 255), np.full((len(m.colors), 1), 255)], axis=1).astype(np.uint8)
    tm = trimesh.Trimesh(vertices=m.vertices, faces=m.faces, vertex_normals=m.normals, vertex_colors=rgba,
                         process=False)
    tm.metadata["name"] = m.name
    scene = trimesh.Scene()
    scene.add_geometry(tm, node_name=m.name, geom_name=m.name)
    data = trimesh.exchange.gltf.export_glb(scene, include_normals=True)
    with open(path, "wb") as fh:
        fh.write(data)


def write_json(m: MeshResult, path: str) -> None:
    obj = dict(
        name=m.name,
        size=m.size.tolist(),
        hinge=None if m.hinge is None else m.hinge.tolist(),
        anchors={k: v.tolist() for k, v in m.anchors.items()},
        positions=np.round(m.vertices, 5).ravel().tolist(),
        normals=np.round(m.normals, 4).ravel().tolist(),
        colors=np.round(m.colors, 4).ravel().tolist(),
        indices=m.faces.ravel().astype(int).tolist(),
    )
    with open(path, "w") as fh:
        json.dump(obj, fh, separators=(",", ":"))


def ensure_dir(path: str) -> None:
    os.makedirs(path, exist_ok=True)
