// Канвас для DOM. px — высота пикселя шрифта в CSS px. opts: стиль PIX.* или свои {fill, outline, outlineW (CSS px)}.
export function pixCanvas(str, px, o = {}, canvas = null) {
  str = String(str);
  const dpr = Math.min(3, window.devicePixelRatio || 1);
  const P = Math.max(1, Math.round(px * dpr));
  const owCss = o.outlineW ?? (o.outlinePx ?? 0) + (o.outlineK || 0) * px;
  const OW = o.outline && owCss > 0 ? Math.max(1, Math.round(owCss * dpr)) : 0;
  const sp = o.spacing ?? 1;
  const rows = o.rows ?? pixRows(str);
  const W = Math.ceil(measurePixText(str, P, { spacing: sp })) + OW * 2, H = rows * P + OW * 2;
  const c = canvas || document.createElement('canvas');
  if (c.width !== W || c.height !== H) { c.width = Math.max(1, W); c.height = Math.max(1, H); } else c.getContext('2d').clearRect(0, 0, W, H);
  c.style.width = (W / dpr).toFixed(2) + 'px'; c.style.height = (H / dpr).toFixed(2) + 'px';
  c.style.imageRendering = 'pixelated';
  const g = c.getContext('2d');
  if (o.bg) { g.fillStyle = o.bg; g.fillRect(0, 0, W, H); }
  drawPixText(g, str, OW, OW, P, { fill: o.fill || '#fff', outline: o.outline, outlineW: OW, spacing: sp });
  c.cssW = W / dpr; c.cssH = H / dpr;
  return c;
}

// Текстура для спрайтов (размер в пикселях канваса; px — пикселей на клетку шрифта)
export function pixTexture(str, px = 8, o = {}) {
  str = String(str);
  const OW = o.outline ? Math.max(1, Math.round(o.outlineW ?? (o.outlinePx ?? 0) + (o.outlineK || 0) * px)) : 0;
  const sp = o.spacing ?? 1;
  const rows = o.rows ?? pixRows(str);
  const pad = o.pad ?? 2;
  const W = Math.ceil(measurePixText(str, px, { spacing: sp })) + OW * 2 + pad * 2, H = rows * px + OW * 2 + pad * 2;
  const c = document.createElement('canvas'); c.width = W; c.height = H;
  const g = c.getContext('2d');
  drawPixText(g, str, OW + pad, OW + pad, px, { fill: o.fill || '#fff', outline: o.outline, outlineW: OW, spacing: sp });
  const t = new THREE.CanvasTexture(c);
  t.colorSpace = THREE.SRGBColorSpace;
  t.anisotropy = 2;
  t.userData.aspect = W / H;
  return t;
}
